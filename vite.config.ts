import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { defineConfig, type Plugin } from 'vite';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const pkgJson = JSON.parse(
  fs.readFileSync(path.join(__dirname, 'package.json'), 'utf8')
) as { version?: string };
const appVersion = pkgJson.version ?? '0.1.0';

function collectDistFiles(dir: string, rootDir: string): string[] {
  const results: string[] = [];
  if (!fs.existsSync(dir)) return results;

  const entries = fs.readdirSync(dir, { withFileTypes: true });
  for (const entry of entries) {
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      results.push(...collectDistFiles(fullPath, rootDir));
    } else if (entry.isFile()) {
      const rel = path.relative(rootDir, fullPath).split(path.sep).join('/');
      if (rel === 'sw.js' || rel.endsWith('.map')) continue;
      results.push(rel);
    }
  }
  return results;
}

function firstTribesPwaPlugin(version: string): Plugin {
  return {
    name: 'first-tribes-pwa-sw',
    apply: 'build',
    closeBundle() {
      const distDir = path.resolve(__dirname, 'dist');
      if (!fs.existsSync(distDir)) return;

      // Stamp GitHub Pages subpath (e.g. /The-first-tribes/) into dist/manifest.webmanifest
      // so Chrome on Android builds a WebAPK whose start_url & scope launch reliably
      const repoName = process.env.GITHUB_REPOSITORY?.split('/')[1];
      const manifestBase = repoName ? `/${repoName}/` : './';
      const manifestPath = path.join(distDir, 'manifest.webmanifest');
      const baseManifest = fs.existsSync(manifestPath)
        ? (JSON.parse(fs.readFileSync(manifestPath, 'utf8')) as Record<string, unknown>)
        : {};
      delete baseManifest.display_override;

      const stampedManifest = {
        ...baseManifest,
        id: manifestBase,
        name: baseManifest.name ?? 'Первісні Племена',
        short_name: baseManifest.short_name ?? 'Первісні Племена',
        description:
          baseManifest.description ??
          '2.5D стратегія виживання первісного племені з підтримкою гри офлайн.',
        lang: baseManifest.lang ?? 'uk',
        start_url: manifestBase,
        scope: manifestBase,
        display: 'standalone',
        orientation: 'landscape',
        background_color: baseManifest.background_color ?? '#110a06',
        theme_color: baseManifest.theme_color ?? '#1c130c',
        categories: baseManifest.categories ?? ['games', 'strategy'],
        icons: [
          {
            src: `${manifestBase}icons/icon-192.png`,
            sizes: '192x192',
            type: 'image/png',
            purpose: 'any'
          },
          {
            src: `${manifestBase}icons/icon-512.png`,
            sizes: '512x512',
            type: 'image/png',
            purpose: 'any'
          },
          {
            src: `${manifestBase}icons/icon-maskable-512.png`,
            sizes: '512x512',
            type: 'image/png',
            purpose: 'maskable'
          }
        ]
      };
      fs.writeFileSync(manifestPath, `${JSON.stringify(stampedManifest, null, 2)}\n`, 'utf8');

      const files = collectDistFiles(distDir, distDir).sort();
      const hasher = crypto.createHash('sha256');
      for (const rel of files) {
        hasher.update(rel);
        hasher.update(fs.readFileSync(path.join(distDir, rel)));
      }
      const buildHash = hasher.digest('hex').slice(0, 10);
      const cacheName = `first-tribes-v${version}-${buildHash}`;

      const precacheUrls = Array.from(
        new Set(['./', './index.html', ...files.map((rel) => `./${rel}`)])
      );

      const swSource = `/* Auto-generated by firstTribesPwaPlugin */
const CACHE_NAME = '${cacheName}';
const PRECACHE_URLS = ${JSON.stringify(precacheUrls, null, 2)};

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches
      .open(CACHE_NAME)
      .then((cache) => cache.addAll(PRECACHE_URLS))
      .then(() => self.skipWaiting())
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(
          keys
            .filter((key) => key.startsWith('first-tribes-') && key !== CACHE_NAME)
            .map((key) => caches.delete(key))
        )
      )
      .then(() => self.clients.claim())
  );
});

self.addEventListener('message', (event) => {
  if (event.data && event.data.type === 'SKIP_WAITING') {
    self.skipWaiting();
  }
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;

  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;

  // Navigation requests: Network-First, falling back to cached index.html for offline play
  if (req.mode === 'navigate') {
    event.respondWith(
      fetch(req)
        .then((res) => {
          if (res && res.ok) {
            const copy = res.clone();
            caches.open(CACHE_NAME).then((cache) => cache.put('./index.html', copy));
          }
          return res;
        })
        .catch(() =>
          caches
            .match('./index.html', { ignoreSearch: true })
            .then((cached) => cached || caches.match('./', { ignoreSearch: true }))
        )
    );
    return;
  }

  // Static assets, icons & manifest: Cache-First with network fallback
  event.respondWith(
    caches.match(req, { ignoreSearch: true }).then((cached) => {
      if (cached) return cached;
      return fetch(req).then((res) => {
        if (res && res.ok && res.type === 'basic') {
          const copy = res.clone();
          caches.open(CACHE_NAME).then((cache) => cache.put(req, copy));
        }
        return res;
      });
    })
  );
});
`;

      fs.writeFileSync(path.join(distDir, 'sw.js'), swSource, 'utf8');
    }
  };
}

export default defineConfig({
  base: './',
  define: {
    __APP_VERSION__: JSON.stringify(appVersion)
  },
  server: {
    port: 5173,
    strictPort: false
  },
  build: {
    outDir: 'dist',
    assetsInlineLimit: 0
  },
  plugins: [firstTribesPwaPlugin(appVersion)]
});
